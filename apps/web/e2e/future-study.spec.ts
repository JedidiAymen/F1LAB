import { expect, test } from '@playwright/test'

test('future-performance study filters held-out circuits and synchronizes measured prefixes', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Driver DNA/ }).click()
  const study = page.getByLabel('Inductive future performance study')
  await expect(study.getByRole('table', { name: 'Future performance benchmarks' })).toContainText('5.220')
  await expect(study).toContainText('Persistence remained strongest')
  await study.getByLabel('Future study circuit').selectOption({ label: 'Japan' })
  await expect(study.getByLabel('Future selected prediction')).toContainText('Japan')
  await study.getByLabel('Future study model').selectOption('last_completed_lap')
  await expect(study.getByLabel('Future paired comparison')).toContainText('0.000 s')
  await study.getByLabel('Future study model').selectOption('tcn_no_context_seed42')
  await expect(study.getByLabel('Future paired comparison')).toContainText('no head context · last-lap anchor retained')
  await expect(study).toContainText('still adds its learned residual to the last completed lap')
  await study.getByLabel('Future study failure cases').getByRole('button').first().click()
  await expect(study.getByLabel('Future selected prediction')).toContainText('Input cutoff: 20 s')
  await expect(study.getByLabel('Synchronized observed prefixes').getByRole('heading')).toHaveCount(5)
  await study.getByLabel('Future study model').selectOption('tcn_seed42')
  await expect(study.getByRole('heading', { name: /Validation curve/ })).toBeVisible()
  await study.screenshot({ path: testInfo.outputPath('dna-future-desktop.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  await study.getByLabel('Future study circuit').selectOption({ label: 'Australia' })
  await expect(study.getByLabel('Future selected prediction')).toContainText('Australia')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await study.screenshot({ path: testInfo.outputPath('dna-future-mobile.png') })
})
