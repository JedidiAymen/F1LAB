test('paired agent replay compares the same incident and distinguishes citation support', async ({ page }, testInfo) => {
  const mutations: string[] = []
  page.on('request', (request) => { if (request.method() !== 'GET' && request.url().includes('/research/agent')) mutations.push(request.method()) })
  await page.goto('/')
  await page.getByRole('button', { name: 'Research & reliability' }).click()
  const study = page.getByLabel('Paired agent study', { exact: true })
  await expect(study.getByRole('table', { name: 'Paired model scores' })).toContainText('Foundation')
  await expect(study.getByLabel('Paired uncertainty')).toContainText('fault-family bootstrap')
  await study.getByRole('button', { name: /stale model version-s1/ }).click()
  await expect(study.getByLabel('candidate investigation')).toContainText('Correct label')
  await expect(study.getByLabel('baseline investigation')).toContainText('Incorrect label')
  await study.getByLabel('candidate investigation').getByText('t1: incident_checks · cited', { exact: true }).click()
  await expect(study.getByLabel('candidate investigation')).toContainText('pace-v1')
  await study.getByLabel('Paired incident cohort').click()
  await page.getByRole('option', { name: 'Either agent failed', exact: true }).click()
  await study.getByRole('button', { name: /regime shift-s4/ }).click()
  await expect(study.getByLabel('candidate investigation')).toContainText('Cited evidence: contradicted')
  await study.screenshot({ path: testInfo.outputPath('agent-paired-desktop.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await study.screenshot({ path: testInfo.outputPath('agent-paired-mobile.png') })
  expect(mutations).toHaveLength(0)
})

test('paired replay reports unavailable evidence without breaking the workstation', async ({ page }) => {
  await page.route('**/api/v1/research/agent-paired', (route) => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Evidence checksum invalid' }) }))
  await page.goto('/')
  await page.getByRole('button', { name: 'Research & reliability' }).click()
  await expect(page.getByLabel('Paired agent study', { exact: true })).toContainText('Evidence checksum invalid')
  await page.getByRole('button', { name: 'Race Control', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Research & reliability' })).toBeVisible()
})
