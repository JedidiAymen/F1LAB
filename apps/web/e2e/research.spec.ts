import { expect, test } from '@playwright/test'

test('research observatory filters real failure cases and exposes provenance on desktop and mobile', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Research & reliability' }).click()
  await expect(page.getByRole('heading', { name: 'Research & reliability' })).toBeVisible()
  await expect(page.getByLabel('Evidence verdict')).toContainText('No reliable gain established')
  await expect(page.getByLabel('Benchmark candidates')).toContainText('persistence last lap')
  await page.getByLabel('Research season').click()
  await page.getByRole('option', { name: '2026', exact: true }).click()
  await expect(page.getByLabel('Selected failure')).toContainText('2026')
  await page.getByLabel('Race failure cases').getByRole('button').nth(1).click()
  await expect(page.getByLabel('Selected failure')).toContainText('scored laps')
  await page.getByText('Source hashes and feature availability', { exact: true }).click()
  await expect(page.getByLabel('Model lineage')).toContainText('scenario input for lap L+1')
  await expect(page.getByLabel('Agent investigation replay')).toContainText('25% root-cause accuracy')
  await page.getByLabel('Saved incident').click()
  await page.getByRole('option', { name: 'config_drift-s1', exact: true }).click()
  await expect(page.getByLabel('Incident evidence')).toContainText('Correct diagnosis: config drift')
  await page.getByText('t3: config_diff', { exact: true }).click()
  await expect(page.getByLabel('Incident evidence')).toContainText('green_laps_only')
  await page.screenshot({ path: testInfo.outputPath('research-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByLabel('Research season')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('research-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: 'Race Control', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Research & reliability' })).toBeVisible()
})

test('Three.js code loads only when the existing 3D view is requested', async ({ page }) => {
  const chunks: string[] = []
  page.on('request', (request) => { if (request.url().includes('Circuit3D-') || request.url().includes('/Circuit3D.tsx')) chunks.push(request.url()) })
  await page.goto('/')
  await expect(page.getByRole('button', { name: /Open 3D view/ })).toBeVisible()
  expect(chunks).toHaveLength(0)
  await page.getByRole('button', { name: /Open 3D view/ }).click()
  await expect(page.getByRole('button', { name: 'Orbit', exact: true })).toBeVisible()
  expect(chunks.length).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Orbit', exact: true }).click()
})
